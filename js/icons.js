  function svg(name, size = 16, color = 'currentColor', color2 = null) {
    const g = G[name] || G.star;
    let rects = '';
    g.forEach((row, y) => { for (let x = 0; x < 8; x++) {
      const ch = row[x]; if (ch === '.') continue;
      rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${ch === '+' ? (color2 || '#ffffff') : color}"/>`;
    } });
    return `<svg class="pxi" width="${size}" height="${size}" viewBox="0 0 8 8" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
  }

  function mount(root = document) {
    root.querySelectorAll('i[data-icon]').forEach(el => {
      const size = el.dataset.size || 16;
      el.innerHTML = svg(el.dataset.icon, size, el.dataset.color || 'currentColor', el.dataset.color2 || null);
    });
  }

  global.Icons = { svg, mount, names: Object.keys(G) };
